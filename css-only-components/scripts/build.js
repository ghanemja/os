const indent = (text, n) => text.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');

export function buildGallery(root = ROOT) {
  const comps = listComponents(root).map((n) => readComponent(n, root));
  const toc = comps.map((c) => `      <li><a href="#c-${c.name}">${c.title}</a></li>`).join('\n');
  const sections = comps.map((c) => `
  <section id="c-${c.name}">
    <h2>${c.title}</h2>
    <p>${escapeHtml(c.description)}</p>
    <div class="demo">
${indent(c.html, 6)}
    </div>
    <p class="links"><a href="components/${c.name}/index.html">Open demo and accessibility notes</a></p>
    <div class="code">
      <h3>HTML</h3>
      <button type="button" class="copy" data-copy="code-${c.name}-html">Copy</button>
      <pre><code id="code-${c.name}-html">${escapeHtml(c.html)}</code></pre>
    </div>
    <div class="code">
      <h3>CSS</h3>
      <button type="button" class="copy" data-copy="code-${c.name}-css">Copy</button>
      <pre><code id="code-${c.name}-css">${escapeHtml(c.css.trimEnd())}</code></pre>
    </div>
  </section>`).join('\n');

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>css-only-components</title>
  <meta name="description" content="${comps.length} UI components built with HTML and CSS only: no JavaScript.">
  <link rel="stylesheet" href="${CSS_FILE}">
  <style>${PAGE_CSS}
  </style>
</head>
<body>
<!-- Generated by scripts/build.js. Do not edit by hand. -->
<header>
  <h1>css-only-components</h1>
  <p>${comps.length} UI components that need zero JavaScript. Copy the HTML and CSS, or include <code>${CSS_FILE}</code>. Each one has its own demo page with honest accessibility notes.</p>
  <nav aria-label="Components">
    <ul class="toc">
${toc}
    </ul>
  </nav>
</header>
<main>
${sections}
</main>
<footer>
  <p>MIT License &copy; 2026 ghanemja. The components use no JavaScript; this gallery page uses a few lines only for the Copy buttons.</p>
</footer>
<script>
  document.addEventListener('click', async (event) => {
    const btn = event.target.closest('[data-copy]');
    if (!btn) return;
    const code = document.getElementById(btn.dataset.copy);
    try {
      await navigator.clipboard.writeText(code.textContent);
      btn.textContent = 'Copied';
    } catch {
      getSelection().selectAllChildren(code);
      btn.textContent = 'Press Ctrl+C';
    }
    setTimeout(() => { btn.textContent = 'Copy'; }, 1500);
  });
</script>
</body>
</html>
`;
}

export function outputs(root = ROOT) {
  return { [CSS_FILE]: buildCss(root), [GALLERY_FILE]: buildGallery(root) };
}

function main(argv) {
  const check = argv.includes('--check');
  let stale = 0;
  for (const [file, content] of Object.entries(outputs())) {
    const path = join(ROOT, file);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === content) continue;
    if (check) {
      console.error(`${file} is out of date. Run: npm run build`);
      stale++;
    } else {
      writeFileSync(path, content);
      console.log(`wrote ${file}`);
    }
  }
  if (check && !stale) console.log('build outputs are up to date');
  return stale ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exitCode = main(process.argv.slice(2));
}
