#!/usr/bin/env node
// Builds css-only-components.css (all component styles in one file) and the
// index.html gallery from components/<name>/{index.html,style.css}.
//
//   node scripts/build.js          write both files
//   node scripts/build.js --check  exit 1 if either file is out of date

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CSS_FILE = 'css-only-components.css';
export const GALLERY_FILE = 'index.html';

export function listComponents(root = ROOT) {
  const dir = join(root, 'components');
  return readdirSync(dir).filter((n) => statSync(join(dir, n)).isDirectory()).sort();
}

const between = (s, a, b) => {
  const i = s.indexOf(a);
  const j = s.indexOf(b, i + a.length);
  return i === -1 || j === -1 ? null : s.slice(i + a.length, j);
};

export function dedent(text) {
  const lines = text.replace(/^\s*\n/, '').replace(/\s+$/, '').split('\n');
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length));
  return lines.map((l) => l.slice(indent)).join('\n');
}

const unescapeHtml = (s) => s
  .replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
export const escapeHtml = (s) => s
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function readComponent(name, root = ROOT) {
  const dir = join(root, 'components', name);
  const page = readFileSync(join(dir, 'index.html'), 'utf8');
  const css = readFileSync(join(dir, 'style.css'), 'utf8');
  const snippet = between(page, '<!-- snippet:start -->', '<!-- snippet:end -->');
  if (snippet === null) throw new Error(`components/${name}/index.html has no snippet markers`);
  const title = (page.match(/<h1>([\s\S]*?)<\/h1>/) || [])[1];
  const desc = (page.match(/<meta name="description" content="([^"]*)">/) || [])[1];
  if (!title || !desc) throw new Error(`components/${name}/index.html needs an <h1> and a meta description`);
  return { name, title: title.trim(), description: unescapeHtml(desc), html: dedent(snippet), css: css.trimEnd() + '\n' };
}

export function buildCss(root = ROOT) {
  const parts = listComponents(root).map((name) => {
    const { css } = readComponent(name, root);
    return `/* ==== ${name} (components/${name}/style.css) ==== */\n${css}`;
  });
  return [
    '/*! css-only-components | MIT License | https://github.com/ghanemja/css-only-components */',
    '/* Generated by scripts/build.js from components/<name>/style.css. Do not edit by hand. */',
    '',
    parts.join('\n'),
  ].join('\n');
}

